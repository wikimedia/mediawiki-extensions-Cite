require( '@cypress/skip-test/support' );
import * as helper from './../../utils/functions.helper.js';
import * as veHelper from './../../utils/ve.helper.js';

let usesCitoid;

describe( 'VisualEditor Cite - Autonames', () => {
	before( () => {
		veHelper.checkModuleDependencies().then( ( deps ) => {
			cy.skipOn( !deps.visualEditor );
			usesCitoid = deps.citoid;
		} );
	} );

	beforeEach( () => {
		cy.session( 've-cite-integration', () => {
			cy.clearCookies();
			veHelper.setVECookiesToDisableDialogs();
		} );
	} );

	// Fixtures (templates, mapping of templates) in setup/setup.js
	it( 'should be able to insert new autonamed references in Visual Editor', () => {

		// Create & edit test page
		const title = helper.getTestString( 'CiteTest-title' );
		helper.editPage( title, 'A claim <ref>{{Literatur|title=Test Book|lastname=Smith}}</ref>\n\nAnother line' );
		veHelper.openVEForEditingReferences( title, usesCitoid );

		// Check that reference really exists on the page
		veHelper.getRefsFromArticleSection().should( 'have.length', 1 );

		// Open reuse dialog and insert first item, checking that its contents renders correctly
		// We reuse the reference to trigger a named reference
		if ( usesCitoid ) {
			veHelper.openVECitoidReuseDialog();
		} else {
			// Applying the first reference leaves it selected. Move the cursor after it
			// so choosing a reused reference inserts rather than replaces it.
			cy.get( '.ve-ui-surface' ).type( '{rightarrow} Test ' );
			veHelper.openVECiteReuseDialog();
		}
		veHelper.getCiteReuseDialogRefResult( 1 )
			.should( 'contain.text', 'Smith Test Book' )
			.click();

		// Check that another reference was inserted
		veHelper.getRefsFromArticleSection().should( 'have.length', 2 );

		// Switch to WikiText Editor
		cy.get( '#p-views #ca-edit' ).click();

		// Assert that the Wikitext contains ref with autogenerated reference
		cy.get( 'textarea[name="wpTextbox1"]' )
			.should( 'contain.value', 'name="Smith-Test Book-1"' );
	} );

} );
